// Generates the plan-limits block of supabase/migrations/002_plans_admin_emails.sql
// from shared/plans.js, so the database limits can never drift from the
// prices / limits the app shows.
//
//   node scripts/gen-plan-sql.mjs          → print the block
//   node scripts/gen-plan-sql.mjs --write  → rewrite it in the migration
//   node scripts/gen-plan-sql.mjs --check  → exit 1 if the migration is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TIERS, TRIAL_TIER, FOUNDER_LIFETIME_CAP, UNCOUNTED_INVOICE_TYPES } from '../shared/plans.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MIGRATION = path.join(root, 'supabase/migrations/002_plans_admin_emails.sql');
export const SETUP = path.join(root, 'supabase-setup.sql');
export const SETUP_MARKER = '-- PHASE 2 (verbatim copy of supabase/migrations/002_plans_admin_emails.sql — regenerate with: node scripts/gen-plan-sql.mjs --write)';
const BEGIN = '-- >>> GENERATED by scripts/gen-plan-sql.mjs from shared/plans.js — do not edit by hand';
const END = '-- <<< END GENERATED';

const lit = (v) => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

export function generateBlock() {
  const rows = Object.values(TIERS).map(t =>
    `  (${lit(t.id)}, ${t.rank}, ${lit(t.limits.invoicesPerMonth)}, ${lit(t.limits.businesses)}, ${lit(t.limits.staffUsers)}, ${lit(JSON.stringify(t.features))}::jsonb)`);
  return [
    BEGIN,
    'INSERT INTO public.plan_limits (tier, rank, invoices_per_month, businesses, staff_users, features) VALUES',
    rows.join(',\n'),
    'ON CONFLICT (tier) DO UPDATE SET rank = EXCLUDED.rank, invoices_per_month = EXCLUDED.invoices_per_month,',
    '  businesses = EXCLUDED.businesses, staff_users = EXCLUDED.staff_users, features = EXCLUDED.features, updated_at = NOW();',
    '',
    'CREATE OR REPLACE FUNCTION public.gbp_plan_const(p_key TEXT) RETURNS TEXT',
    'LANGUAGE sql IMMUTABLE SET search_path = public AS $fn$',
    '  SELECT CASE p_key',
    `    WHEN 'trial_tier' THEN ${lit(TRIAL_TIER)}`,
    `    WHEN 'founder_cap' THEN ${lit(String(FOUNDER_LIFETIME_CAP))}`,
    `    WHEN 'uncounted_invoice_types' THEN ${lit(UNCOUNTED_INVOICE_TYPES.join(','))}`,
    '  END',
    '$fn$;',
    END,
  ].join('\n');
}

export function currentBlock(sql) {
  const a = sql.indexOf(BEGIN), b = sql.indexOf(END);
  if (a < 0 || b < 0) return null;
  return sql.slice(a, b + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const block = generateBlock();
  const mode = process.argv[2];
  if (!mode) { console.log(block); process.exit(0); }
  const sql = fs.readFileSync(MIGRATION, 'utf8');
  const cur = currentBlock(sql);
  if (cur == null) { console.error('generated markers not found in', MIGRATION); process.exit(1); }
  if (mode === '--check') {
    if (cur !== block) { console.error('002 migration plan block is stale — run: node scripts/gen-plan-sql.mjs --write'); process.exit(1); }
    if (!fs.readFileSync(SETUP, 'utf8').includes(sql.trim())) { console.error('supabase-setup.sql is missing the current 002 copy — run: node scripts/gen-plan-sql.mjs --write'); process.exit(1); }
    console.log('plan SQL in sync'); process.exit(0);
  }
  if (mode === '--write') {
    const next = sql.replace(cur, block);
    fs.writeFileSync(MIGRATION, next);
    const setup = fs.readFileSync(SETUP, 'utf8');
    const i = setup.indexOf(SETUP_MARKER);
    const head = i >= 0 ? setup.slice(0, i) : setup.replace(/\s*$/, '\n\n');
    fs.writeFileSync(SETUP, `${head}${SETUP_MARKER}\n${next.trim()}\n`);
    console.log('updated', MIGRATION, 'and', SETUP);
  }
}
